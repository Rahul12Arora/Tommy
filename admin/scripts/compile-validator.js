import { mkdirSync, writeFileSync } from "node:fs";
import { compileSchemaValidatorsCode } from "@rjsf/validator-ajv8/compileSchemaValidators";
import schema from "../../shared/config.schema.json" with { type: "json" };

/**
 * Compiles shared/config.schema.json into plain validation functions, before every dev start and build
 * (ARCHITECTURE §14.11, D-140). Ajv normally builds them in the browser with `new Function`, which the console's
 * Content Security Policy (script-src 'self', no 'unsafe-eval') forbids.
 * Ajv's ES-module output can't be used (RJSF names each function after a hash that may start with a digit), so the
 * CommonJS output is wrapped into a module with one default export. It needs no imports of its own.
 */
const OUTPUT_DIR = new URL("../src/generated/", import.meta.url);

const commonJs = compileSchemaValidatorsCode(schema).replace(/^"use strict";\n/, "");
const module = [
  "// Generated by scripts/compile-validator.js from shared/config.schema.json. Don't edit; not committed.",
  "const exports = {};",
  commonJs,
  "export default exports;",
  "",
].join("\n");

mkdirSync(OUTPUT_DIR, { recursive: true });
writeFileSync(new URL("configValidator.js", OUTPUT_DIR), module);
console.log("compiled src/generated/configValidator.js");
